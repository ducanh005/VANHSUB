import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createTtsRunDirectory } from '../main/render/ttsCache';

const project = fs.mkdtempSync(path.join(os.tmpdir(), 'vanhsub-cache-seed-'));
const previous = path.join(project, 'previous');
fs.mkdirSync(previous);
fs.writeFileSync(path.join(previous, 'manifest.json'), JSON.stringify({
  '1': { isGroupLeader: true }, '2': { isGroupMember: true, leaderIndex: 1 }, '3': { text: 'standalone' },
  '4': { isGroupMember: true, leaderIndex: '../outside' }, '../outside': { text: 'invalid key' },
}));
for (const name of ['subtitle_0001.mp3', 'subtitle_0002.mp3', 'subtitle_0003.mp3', 'subtitle_9999.mp3']) fs.writeFileSync(path.join(previous, name), name);
const seeded = createTtsRunDirectory(project, previous);
assert.deepEqual(fs.readdirSync(seeded).sort(), ['manifest.json', 'subtitle_0001.mp3', 'subtitle_0003.mp3']);
fs.writeFileSync(path.join(seeded, 'subtitle_0001.mp3'), 'new generated bytes');
assert.equal(fs.readFileSync(path.join(previous, 'subtitle_0001.mp3'), 'utf8'), 'subtitle_0001.mp3', 'Seed must not hard-link completed audio');
fs.writeFileSync(path.join(previous, 'manifest.json'), 'corrupt');
assert.deepEqual(fs.readdirSync(createTtsRunDirectory(project, previous)), []);
fs.writeFileSync(path.join(previous, 'manifest.json'), '[]');
assert.deepEqual(fs.readdirSync(createTtsRunDirectory(project, previous)), []);
console.log('PASS: referenced master seeding, no member/orphan copies, immutable prior run and corrupt-manifest cold start');
